"""Mirror docs/todo.md onto the live To-do page (tools/todo/, Supabase table todos).

docs/todo.md is the master copy. This prints SQL that replaces every open row in
`todos` with the items in todo.md; rows ticked done on the page are kept. Run it in
the Supabase SQL Editor or through the Supabase MCP (project "GVC Tools").

    python scripts/sync_todo.py            # print the SQL
    python scripts/sync_todo.py --copy     # also copy it to the clipboard (Windows)

Before running it, read the table: anything added or ticked on the page since the
last sync must go into todo.md first, or the delete below loses it.

"Start here", "Done recently" and the two decision-record sections are not synced.
"""
import re
import subprocess
import sys
from pathlib import Path

# Notes for Claude, history and settled decisions: not tasks, so not synced
SKIP = ('Start here', 'Done recently', 'Destination Guide decisions', "Matt's standing decisions")
# todo.md heading (up to any " (") -> the shorter name the page uses
PAGE_NAME = {'Up next': 'Up next', 'From Asana, open tasks': 'From Asana',
             "Matt's new to-dos": "Matt's to-dos",
             'Brochure and site audit follow-ups': 'Brochure and site audit'}
TODO = Path(__file__).resolve().parent.parent / 'docs' / 'todo.md'
BULLET = '\n• '


def plain(text):
    """Markdown to the plain text the page shows."""
    text = re.sub(r'\*\*(.+?)\*\*', r'\1', text)
    text = re.sub(r'`([^`]+)`', r'\1', text)
    return re.sub(r'\s+', ' ', text).strip()


def items(md):
    """[section, body] rows. Sub-bullets join their parent's row as bullet lines."""
    section, out = None, []
    for line in md.splitlines():
        if line.startswith('## '):
            section = line[3:].strip()
            section = PAGE_NAME.get(section.split(' (')[0], section)
            continue
        if section is None or section.startswith(SKIP):
            continue
        top = re.match(r'^(?:-|\d+\.) (.+)', line)
        sub = re.match(r'^\s{2,}- (.+)', line)
        if top:
            out.append([section, plain(top.group(1))])
        elif sub and out:
            out[-1][1] += BULLET + plain(sub.group(1))
    return out


def quote(s):
    """A Postgres string literal (standard strings: only ' needs doubling)."""
    return "'" + s.replace("'", "''") + "'"


def sql(rows):
    values = ',\n'.join('  (%s, %s, %d)' % (quote(s), quote(b), i)
                        for i, (s, b) in enumerate(rows))
    return '\n'.join(['-- Generated by scripts/sync_todo.py from docs/todo.md', 'begin;',
                      'delete from public.todos where done = false;',
                      'insert into public.todos (section, body, position) values',
                      values + ';', 'commit;'])


if __name__ == '__main__':
    sys.stdout.reconfigure(encoding='utf-8')
    out = sql(items(TODO.read_text(encoding='utf-8')))
    print(out)
    if '--copy' in sys.argv:
        subprocess.run('clip', input=out.encode('utf-16'), check=True)
        print('\n-- copied to clipboard', file=sys.stderr)
